--- Write a license file to the target path.
---@param license_key string "CC0-1.0" | "MIT" | "GPL-3.0" | "Apache-2.0" | "BSD-3-Clause" | "Unlicense"
---@param target_path? string default: "./LICENSE"
---@param author? string
---@param year? string
---@return boolean success, string message
function M.write_license(license_key, target_path, author, year)
  target_path = target_path or "LICENSE"
  local lic = M.LICENSES[license_key]
  if not lic then
    return false, "Unknown license key: " .. tostring(license_key)
  end

  author = author or vim.fn.system("git config user.name"):gsub("%s+$", "")
  if author == "" then author = "Author" end
  year = year or os.date("%Y")

  local content = lic.generate(author, year)
  local f = io.open(target_path, "w")
  if not f then
    return false, "Failed to write license to " .. target_path
  end
  f:write(content)
  f:close()
  return true, "Wrote " .. lic.name .. " to " .. target_path
end

